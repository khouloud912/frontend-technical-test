import { useMutation, useQueryClient } from '@tanstack/react-query'
import { sendMessage } from '@/api/messages'
import { queryKeys } from '@/api/queryKeys'
import { messageBodySchema } from '@/api/schemas'
import { useLoggedUserId } from '@/context/AuthContext'
import type { Conversation } from '@/types/conversation'
import type { ThreadMessage } from '@/types/message'
import { toUnixSeconds } from '@/utils/formatDate'

interface SendVariables {
  /** Negative temporary id of the optimistic message (reused on retry). */
  tempId: number
  body: string
  timestamp: number
}

// Negative ids can never collide with ids generated by the server
let lastTempId = 0
const nextTempId = () => --lastTempId

/** Optimistic: shown at once as "sending", kept as "failed" (with retry) on error. */
export function useSendMessage(conversationId: number) {
  const queryClient = useQueryClient()
  const authorId = useLoggedUserId()
  const messagesKey = queryKeys.messages.byConversation(conversationId)

  const updateMessages = (update: (messages: ThreadMessage[]) => ThreadMessage[]) =>
    queryClient.setQueryData<ThreadMessage[]>(messagesKey, (messages = []) => update(messages))

  const mutation = useMutation({
    mutationKey: ['sendMessage', conversationId],
    mutationFn: ({ body, timestamp }: SendVariables) =>
      sendMessage({ conversationId, authorId, body, timestamp }),

    onMutate: async ({ tempId, body, timestamp }) => {
      // An in-flight refetch must not overwrite the optimistic message
      await queryClient.cancelQueries({ queryKey: messagesKey })
      const optimistic: ThreadMessage = {
        id: tempId,
        conversationId,
        authorId,
        body,
        timestamp,
        status: 'sending',
      }
      updateMessages((messages) => [
        ...messages.filter((message) => message.id !== tempId),
        optimistic,
      ])
    },

    onSuccess: (saved, { tempId }) => {
      // Swap the temporary message for the saved one (no flicker, no duplicate)
      updateMessages((messages) => [
        ...messages.filter((message) => message.id !== tempId && message.id !== saved.id),
        saved,
      ])
      // The server does not update the conversation: move it to the top ourselves
      queryClient.setQueryData<Conversation[]>(
        queryKeys.conversations.byUser(authorId),
        (conversations) =>
          conversations?.map((conversation) =>
            conversation.id === conversationId
              ? {
                  ...conversation,
                  lastMessageTimestamp: Math.max(
                    conversation.lastMessageTimestamp,
                    saved.timestamp,
                  ),
                }
              : conversation,
          ),
      )
    },

    onError: (_error, { tempId }) => {
      // Not rolled back: the message stays visible so the user can retry it
      updateMessages((messages) =>
        messages.map((message) =>
          message.id === tempId ? { ...message, status: 'failed' } : message,
        ),
      )
    },

    onSettled: () => {
      void queryClient.invalidateQueries({ queryKey: messagesKey })
      void queryClient.invalidateQueries({ queryKey: queryKeys.conversations.all })
    },
  })

  /** Returns false (and sends nothing) if the message is blank, too long, or a send is pending. */
  const send = (body: string): boolean => {
    const parsed = messageBodySchema.safeParse(body)
    if (!parsed.success || mutation.isPending) return false
    mutation.mutate({ tempId: nextTempId(), body: parsed.data, timestamp: toUnixSeconds() })
    return true
  }

  const retry = (message: ThreadMessage) => {
    if (message.status !== 'failed' || mutation.isPending) return
    mutation.mutate({ tempId: message.id, body: message.body, timestamp: toUnixSeconds() })
  }

  return { send, retry, isPending: mutation.isPending }
}
